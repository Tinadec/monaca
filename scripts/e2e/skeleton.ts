// `bun run e2e:skeleton --base-url <url>` — the single acceptance script (contract §12, plan §13).
//
// Stage 0 is implemented here: the target must answer `GET /healthz` with `{"status":"ok"}`.
// The five M0 acceptance steps are printed as TODOs; they are implemented in the next run, once
// the server and the demo MCP module exist. The script works against any origin: localhost:8080,
// the deployed dev gateway, or the CI server started from the `server-*` artifact.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { describeNetError } from "../lib/net.ts";

const ROOT = join(import.meta.dir, "..", "..");
const REPORT = join(ROOT, ".monaca", "reports", "skeleton.json");

/** One entry per contract §12 row. `step` matches the contract's numbering. */
